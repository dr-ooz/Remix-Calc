// Builds src/js/remix_species_data.js from remix-data/pokedex.json + abilities.json (extractor files, as-is).
// REMIX_SINGLE_ABILITY: Pokemon whose Remix data lists exactly one distinct ability. Blank sets only
// auto-fill the ability for these (e.g. Shedinja = Wonder Guard); everyone else starts blank.
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const read = f => JSON.parse(fs.readFileSync(path.join(ROOT, "remix-data", f), "utf8"));
const dex = read("pokedex.json");
const abilities = read("abilities.json");

const single = {};
for (const d of dex) {
	const name = d.species + (d.form ? "-" + d.form.replace(/ /g, "-") : "");
	const names = [...new Set((d.abilities || []).map(i => abilities[i] && abilities[i][0]).filter(Boolean))];
	if (names.length === 1) single[name] = names[0];
}
fs.writeFileSync(path.join(ROOT, "src", "js", "remix_species_data.js"),
	"// GENERATED by tools/build_remix_species.js from remix-data/. Do not edit by hand.\n" +
	"var REMIX_SINGLE_ABILITY = " + JSON.stringify(single, null, 1) + ";\n" +
	"// Ability a blank set should start with: the only ability if there's just one, otherwise blank.\n" +
	"function remixBlankAbility(name) { return REMIX_SINGLE_ABILITY[name] || \"\"; }\n");
console.log("Remix species: " + Object.keys(single).length + " single-ability Pokemon -> src/js/remix_species_data.js");
