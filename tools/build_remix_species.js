// Builds src/js/remix_species_data.js from remix-data/pokedex.json + abilities.json (extractor files, as-is).
// REMIX_SINGLE_ABILITY: Pokemon whose Remix data lists exactly one distinct ability. Blank sets only
// auto-fill the ability for these (e.g. Shedinja = Wonder Guard); everyone else starts blank.
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const read = f => JSON.parse(fs.readFileSync(path.join(ROOT, "remix-data", f), "utf8"));
const dex = read("pokedex.json");
const abilities = read("abilities.json").map(a => [String(a[0]).replace(/’/g, "'"), a[1]]); // extractor uses curly apostrophes

const RENAMES = read("species_renames.json").rename || {};
const single = {};
for (const d of dex) {
	const raw = d.species + (d.form ? "-" + d.form.replace(/ /g, "-") : "");
	const name = RENAMES[raw] || raw; // the calc's name for it (renamed Pokemon)
	const names = [...new Set((d.abilities || []).map(i => abilities[i] && abilities[i][0]).filter(Boolean))];
	if (names.length === 1) single[name] = names[0];
}
fs.writeFileSync(path.join(ROOT, "src", "js", "remix_species_data.js"),
	"// GENERATED by tools/build_remix_species.js from remix-data/. Do not edit by hand.\n" +
	"var REMIX_SINGLE_ABILITY = " + JSON.stringify(single, null, 1) + ";\n" +
	"// Ability a blank set should start with: the only ability if there's just one, otherwise blank.\n" +
	"function remixBlankAbility(name) { return REMIX_SINGLE_ABILITY[name] || \"\"; }\n");
// Gen 7 ability list = the game's own names (remix-data/abilities.json). The two leftover "OLD ..." slots are skipped.
const abilityNames = [...new Set(abilities.map(a => a[0]).filter(n => n && !/^OLD /.test(n)))];
fs.writeFileSync(path.join(ROOT, "calc", "src", "data", "remix_abilities.ts"),
	"// GENERATED by tools/build_remix_species.js from remix-data/abilities.json. Do not edit by hand.\n" +
	"export const REMIX_ABILITIES: string[] = " + JSON.stringify(abilityNames, null, 1) + ";\n");
console.log("Remix abilities: " + abilityNames.length + " -> calc/src/data/remix_abilities.ts");
console.log("Remix species: " + Object.keys(single).length + " single-ability Pokemon -> src/js/remix_species_data.js");

// Species renames/removals (remix-data/species_renames.json) -> calc data + browser global (search aliases, sprites).
const renames = read("species_renames.json");
const renameData = {remove: renames.remove || [], rename: renames.rename || {}};
fs.writeFileSync(path.join(ROOT, "calc", "src", "data", "remix_species_renames.ts"),
	"// GENERATED by tools/build_remix_species.js from remix-data/species_renames.json. Do not edit by hand.\n" +
	"export const REMIX_SPECIES_RENAMES: {remove: string[]; rename: {[old: string]: string}} = " +
	JSON.stringify(renameData, null, 1) + ";\n");
fs.writeFileSync(path.join(ROOT, "src", "js", "remix_species_renames.js"),
	"// GENERATED by tools/build_remix_species.js from remix-data/species_renames.json. Do not edit by hand.\n" +
	"var REMIX_SPECIES_RENAMES = " + JSON.stringify(renameData, null, 1) + ";\n");
console.log("Remix species renames: " + Object.keys(renameData.rename).length + " renamed, " + renameData.remove.length + " removed");

// Personal data (remix-data/pokedex.json, straight from the extractor) -> types + base stats for the calc.
// Drop in a new pokedex.json and rebuild to update every Pokemon. Names are "Species-Form" with the
// game's own names; species.ts matches them loosely (case/punctuation) after the renames are applied.
const TYPE_NAMES = ["Normal", "Fighting", "Flying", "Poison", "Ground", "Rock", "Bug", "Ghost", "Steel",
	"Fire", "Water", "Grass", "Electric", "Psychic", "Ice", "Dragon", "Dark", "Fairy"];
const personal = {};
for (const d of dex) {
	const name = d.species + (d.form ? "-" + d.form.replace(/ /g, "-") : "");
	const types = [...new Set((d.types || []).map(t => TYPE_NAMES[t]).filter(Boolean))];
	const s = d.baseStats || [];
	if (personal[name]) continue; // first entry wins (duplicate form slots)
	personal[name] = {types, bs: {hp: s[0], at: s[1], df: s[2], sa: s[3], sd: s[4], sp: s[5]}};
}
fs.writeFileSync(path.join(ROOT, "calc", "src", "data", "remix_personal.ts"),
	"// GENERATED by tools/build_remix_species.js from remix-data/pokedex.json. Do not edit by hand.\n" +
	"export const REMIX_PERSONAL: {[name: string]: {types: string[]; bs: {[s: string]: number}}} = " +
	JSON.stringify(personal) + ";\n");
console.log("Remix personal data: " + Object.keys(personal).length + " entries -> calc/src/data/remix_personal.ts");
