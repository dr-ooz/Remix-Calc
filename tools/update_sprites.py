"""Refresh the calc's minisprites from the Swelt extractor output.

Usage:  python tools/update_sprites.py "<path to swelt-in_EXTRACTED_DATA>"

icons.webp is a 32-column grid of 40x30 icons in game order: cell N = a/0/6/2
entry N+1 (entry 0 is the blank icon). tools/sprite_slots.json maps each calc
sprite file name (e.g. "giratina-origin") to its a/0/6/2 entry. The extension
uses the same names with the hyphens removed ("giratinaorigin").
"""
import colorsys, json, os, sys, time
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "dist", "img", "pokesprite")
COLS, W, H = 32, 40, 30

def glow_color(icon):
    """Most common vivid color in the sprite, brightened; None if it's mostly grey."""
    bins = {}
    px = icon.tobytes()
    for r, g, b, a in zip(px[0::4], px[1::4], px[2::4], px[3::4]):
        if a < 128:
            continue
        h, sat, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
        if v < 0.25 or sat < 0.22:  # skip outlines, shadows, greys, whites
            continue
        k = int(h * 24) % 24
        c = bins.setdefault(k, [0, 0.0, 0.0, 0.0])
        c[0] += 0.6 + 0.4 * sat  # mostly area, a little extra for vivid pixels
        c[1] += h; c[2] += sat; c[3] += 1
    if not bins:
        return None
    w, hs, ss, n = max(bins.values(), key=lambda c: c[0])
    if n < 6:
        return None
    r, g, b = colorsys.hsv_to_rgb(hs / n, min(ss / n, 0.85), 1.0)
    # Dark hues (deep blue, purple) barely show on the dark page: lighten them.
    lum = 0.2126 * r + 0.7152 * g + 0.0722 * b
    if lum < 0.6:
        t = (0.6 - lum) / (1 - lum)
        r, g, b = r + (1 - r) * t, g + (1 - g) * t, b + (1 - b) * t
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))

def main(extracted):
    sheet = Image.open(os.path.join(extracted, "icons.webp")).convert("RGBA")
    slots = json.load(open(os.path.join(HERE, "sprite_slots.json")))
    colors = {}
    for name, entry in slots.items():
        cell = entry - 1
        x, y = (cell % COLS) * W, (cell // COLS) * H
        icon = sheet.crop((x, y, x + W, y + H))
        icon.save(os.path.join(OUT, name + ".png"))
        colors[name] = glow_color(icon)
    # New version tag so browsers fetch the new images instead of cached ones.
    with open(os.path.join(HERE, "..", "src", "js", "sprite_version.js"), "w") as f:
        f.write('var REMIX_SPRITE_VERSION = "%d";' % int(time.time()) + chr(10))
    # Hand-picked colors win over the automatic ones.
    overrides = os.path.join(HERE, "glow_overrides.json")
    if os.path.exists(overrides):
        colors.update(json.load(open(overrides)))
    with open(os.path.join(HERE, "..", "src", "js", "sprite_colors.js"), "w") as f:
        f.write("// Generated by tools/update_sprites.py: glow color per sprite (null = white).\n")
        f.write("var REMIX_SPRITE_COLORS = " + json.dumps(colors, sort_keys=True) + ";\n")
    print("wrote", len(slots), "sprites to", os.path.normpath(OUT))
    print("now rebuild the calc: npm run compile")

if __name__ == "__main__":
    main(sys.argv[1])
