// Builds the calc's Gen 7 move table from the files in remix-data/ (runs on every `npm run compile`).
//
// remix-data/moves.json        -> drop in the extractor's moves.json as-is to update moves
// remix-data/move_extras.json  -> fields the extractor doesn't have yet (priority, hits, drain/recoil,
//                                 crit, contact, target, secondary effects, trapping), keyed by move number.
//                                 Refresh from the game with tools/refresh_move_extras.py.
// remix-data/move_effects.json -> hand-mapped special effects, keyed by move name (wins over everything)
//
// Output: calc/src/data/remix_moves.ts (generated, don't edit by hand).
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DATA = path.join(ROOT, "remix-data");
const OUT = path.join(ROOT, "calc", "src", "data", "remix_moves.ts");

const TYPES = ["Normal", "Fighting", "Flying", "Poison", "Ground", "Rock", "Bug", "Ghost", "Steel",
	"Fire", "Water", "Grass", "Electric", "Psychic", "Ice", "Dragon", "Dark", "Fairy"];
const CATEGORIES = ["Status", "Physical", "Special"];
const TARGETS = {4: "allAdjacent", 5: "allAdjacentFoes"}; // anything else is single-target for damage
const isZ = n => (n >= 622 && n <= 658) || (n >= 695 && n <= 703) || n === 719 || (n >= 723 && n <= 728);

const read = f => JSON.parse(fs.readFileSync(path.join(DATA, f), "utf8"));
const moves = read("moves.json");
const extras = read("move_extras.json");
const effects = fs.existsSync(path.join(DATA, "move_effects.json")) ? read("move_effects.json") : {};

const table = {"(No Move)": {bp: 0, category: "Status", type: "Normal"}};
for (const m of moves) {
	const x = extras[String(m.num)] || {};
	const cat = CATEGORIES[m.category];
	const damaging = cat !== "Status";
	const d = {bp: damaging ? m.power : 0, type: TYPES[m.type], category: cat};
	if (m.zPower) d.zp = m.zPower;
	if (m.pp) d.pp = m.pp; // Remix PP counter
	if (x.priority) d.priority = x.priority;
	if (x.hitMax > 1) d.multihit = x.hitMin === x.hitMax ? x.hitMin : [x.hitMin, x.hitMax];
	if (damaging && x.drainRecoil > 0) d.drain = [x.drainRecoil, 100];
	if (damaging && x.drainRecoil < 0) d.recoil = [-x.drainRecoil, 100];
	if (damaging && x.crit >= 6) d.willCrit = true;
	if (damaging && TARGETS[x.target]) d.target = TARGETS[x.target];
	if (x.contact) d.makesContact = true;
	// move flags from the game (tools/refresh_move_extras.py): ability move lists
	const FLAG_FIELDS = {punch: "isPunch", sound: "isSound", bite: "isBite", bullet: "isBullet",
		pulse: "isPulse", slicing: "isSlicing", wind: "isWind"};
	for (const f of x.flags || []) {
		if (FLAG_FIELDS[f]) d[FLAG_FIELDS[f]] = true;
		else d.remix = Object.assign(d.remix || {}, {[f]: true}); // showstopper, dance
	}
	if (damaging && x.crit === 2) d.remix = Object.assign(d.remix || {}, {highCrit: true}); // high crit ratio
	if (damaging && x.secondary) d.secondaries = true;
	if (damaging && x.protect === false && !isZ(m.num)) d.breaksProtect = true; // Z-moves keep the 1/4-through-Protect rule
	if (isZ(m.num)) d.isZ = true;
	if (damaging && x.trap) d.remix = {trap: true};
	const fx = effects[m.name] || {};
	const remix = Object.assign({}, d.remix || {}, fx.remix || {});
	Object.assign(d, fx);
	if (Object.keys(remix).length) d.remix = remix;
	table[m.name] = d;
}

fs.writeFileSync(OUT,
	"// GENERATED by tools/build_remix_moves.js from remix-data/. Do not edit by hand.\n" +
	"export const REMIX_MOVES: {[name: string]: any} = " + JSON.stringify(table, null, 1) + ";\n");
console.log("Remix moves: " + Object.keys(table).length + " -> calc/src/data/remix_moves.ts");
