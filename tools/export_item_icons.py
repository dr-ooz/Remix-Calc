"""Export every item icon from the game files as one PNG per item id.

Usage:  python tools/export_item_icons.py "<Citra mods romfs folder>" "<code.bin>" [out folder]

- Icons:   a/0/6/1 (LZ11 FLIM, 32x32 RGBA5551, tiled)
- Links:   code.bin u32 table at 0x4BC8BC (item id -> a/0/6/1 entry)
- Names:   a/0/3/2 file 40 (item names)

Writes  <out>/bitem_<id>.png  (same naming as PKHeX's 3DS item sprites, so the
folder can be dropped into a PKHeX build too) and src/js/remix_item_icons.js
(item name -> id) for the calc. Default out: dist/img/items.
"""
import json, os, re, struct, sys, unicodedata
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from refresh_ability_names import garc_files, text_lines, clean

TABLE = 0x4BC8BC

# 8x8 tile pixel order (Morton / Z-order)
MORTON = np.zeros(64, int)
for i in range(64):
    x = (i & 1) | ((i >> 2) & 1) << 1 | ((i >> 4) & 1) << 2
    y = ((i >> 1) & 1) | ((i >> 3) & 1) << 1 | ((i >> 5) & 1) << 2
    MORTON[i] = y * 8 + x


def lz11(d):
    assert d[0] == 0x11
    n = d[1] | d[2] << 8 | d[3] << 16; p = 4
    if n == 0: n = int.from_bytes(d[4:8], "little"); p = 8
    o = bytearray()
    while len(o) < n:
        fl = d[p]; p += 1
        for b in range(8):
            if len(o) >= n: break
            if fl & (0x80 >> b):
                a = d[p]; t = a >> 4
                if t == 0:
                    l = ((a & 0xf) << 4 | d[p + 1] >> 4) + 0x11; dist = ((d[p + 1] & 0xf) << 8 | d[p + 2]) + 1; p += 3
                elif t == 1:
                    l = ((a & 0xf) << 12 | d[p + 1] << 4 | d[p + 2] >> 4) + 0x111; dist = ((d[p + 2] & 0xf) << 8 | d[p + 3]) + 1; p += 4
                else:
                    l = t + 1; dist = ((a & 0xf) << 8 | d[p + 1]) + 1; p += 2
                for _ in range(l): o.append(o[-dist])
            else:
                o.append(d[p]); p += 1
    return bytes(o)


def decode_icon(raw):
    d = lz11(raw)
    px = np.frombuffer(d[:2048], "<u2")
    rgba = np.stack([((px >> 11) & 31) * 255 // 31, ((px >> 6) & 31) * 255 // 31,
                     ((px >> 1) & 31) * 255 // 31, (px & 1) * 255], 1).astype(np.uint8)
    img = np.zeros((32, 32, 4), np.uint8); t = 0
    for ty in range(0, 32, 8):
        for tx in range(0, 32, 8):
            tl = np.zeros((64, 4), np.uint8); tl[MORTON] = rgba[t * 64:(t + 1) * 64]
            img[ty:ty + 8, tx:tx + 8] = tl.reshape(8, 8, 4); t += 1
    img[img[..., 3] == 0] = 0  # clean colour under transparent pixels
    # Textures are stored sideways (the game rotates them on screen); turn upright.
    return Image.fromarray(np.ascontiguousarray(np.rot90(img, 1)))


def key(name):
    """Loose name match: 'Never-Melt Ice' == 'NeverMeltIce' == 'never melt ice'."""
    name = unicodedata.normalize("NFD", name)
    return re.sub(r"[^a-z0-9]", "", name.lower())


def main():
    romfs, codebin = sys.argv[1], sys.argv[2]
    out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(HERE, "..", "dist", "img", "items")
    os.makedirs(out, exist_ok=True)
    names = [clean(n).strip() for n in text_lines(garc_files(os.path.join(romfs, "a", "0", "3", "2"))[40])]
    cb = open(codebin, "rb").read()
    links = struct.unpack_from("<%dI" % len(names), cb, TABLE)
    icons = garc_files(os.path.join(romfs, "a", "0", "6", "1"))
    cache, by_name = {}, {}
    for item, sprite in enumerate(links):
        if item == 0 or sprite >= len(icons) or not names[item]:
            continue
        if sprite not in cache:
            cache[sprite] = decode_icon(icons[sprite])
        cache[sprite].save(os.path.join(out, "bitem_%d.png" % item), optimize=True)
        k = key(names[item])
        if k and not names[item].startswith("OLD ") and k not in by_name:
            by_name[k] = item
    js = ("// Generated by tools/export_item_icons.py: loose item name -> game item id.\n"
          "// Icon file: img/items/bitem_<id>.png\n"
          "var REMIX_ITEM_ICON_IDS = " + json.dumps(by_name, separators=(",", ":")) + ";\n")
    for p in ("src", "dist"):
        open(os.path.join(HERE, "..", p, "js", "remix_item_icons.js"), "w", encoding="utf-8").write(js)
    print("wrote %d item icons (%d unique sprites), %d names" % (sum(1 for f in os.listdir(out) if f.startswith("bitem_")), len(cache), len(by_name)))


if __name__ == "__main__":
    main()
