// Builds the calc's Remix item data (runs on every `npm run compile`).
// remix-data/item_effects.json -> what each Remix item does (see its _readme)
// remix-data/item_names.json   -> item names that exist in the game (tools/refresh_item_names.py)
// Output: calc/src/data/remix_items.ts and src/js/remix_item_effects.js (generated, don't edit by hand).
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const read = f => JSON.parse(fs.readFileSync(path.join(ROOT, "remix-data", f), "utf8"));
const effects = read("item_effects.json");
delete effects._readme;
const removed = effects._removed || [];
delete effects._removed;
const gameNames = read("item_names.json");
const header = "// GENERATED by tools/build_remix_items.js from remix-data/. Do not edit by hand.\n";
fs.writeFileSync(path.join(ROOT, "calc", "src", "data", "remix_items.ts"), header +
	"export const REMIX_ITEM_EFFECTS: {[item: string]: any[]} = " + JSON.stringify(effects, null, 1) + ";\n" +
	"export const REMIX_GAME_ITEMS: string[] = " + JSON.stringify(gameNames) + ";\n" +
	"// old names whose code now runs a signature item (not usable in Remix)\n" +
	"export const REMIX_REMOVED_ITEMS: string[] = " + JSON.stringify(removed) + ";\n");
fs.writeFileSync(path.join(ROOT, "src", "js", "remix_item_effects.js"), header +
	"var REMIX_ITEM_EFFECTS = " + JSON.stringify(effects) + ";\n");
console.log("Remix items: " + Object.keys(effects).length + " with effects, " + gameNames.length + " game names");
